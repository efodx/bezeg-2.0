/**
 * Patch `index` (0 to 31) as a 4 x 4 net `P[r][c]` in the source's row-major order. With the fixture's convention
 * `(u, v)` = (row, column), `S(0,0) = P[0][0]`, `S(1,0) = P[3][0]`, `S(0,1) = P[0][3]`, `S(1,1) = P[3][3]`, so the net is a
 * `TensorProductBezierPatch` net as it stands. Raw source coordinates: no lid fitting, Blinn height, or display transform.
 */
export function resolveTeapotPatch(index: number): Xyz[][] {
    if (!Number.isInteger(index) || index < 0 || index >= TEAPOT_PATCH_COUNT) throw new RangeError("Teapot patch index must be an integer from 0 through 31.");
    return Array.from({length: 4}, (_, r) => Array.from({length: 4}, (_, c): Xyz => {
        const point = teapotPatches[index * 16 + r * 4 + c] * 3;
        return [teapotVertices[point], teapotVertices[point + 1], teapotVertices[point + 2]];
    }));
}

/** The control points of all 32 patches (the capstone's framing set). */
export const teapotControlPoints = (): Xyz[] => Array.from({length: TEAPOT_PATCH_COUNT}, (_, k) => resolveTeapotPatch(k).flat()).flat();
